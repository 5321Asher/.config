def apply(theme, openrgb=True, settings=None, cell_ratio=2.4):
    """Write every app's colours from a loaded theme dict (see ~/.config/theme/theme)."""
    global HEAD
    HEAD = f"Generated from the {theme['name']} theme by ~/.config/theme/theme"
    p, ansi, syn = complete(theme)
    appearance = theme.get("appearance", "dark")

    fonts, cursor = fonts_for(theme), cursor_for(theme)
    style = setup_style()
    ctx = style_ctx(fonts, appearance)
    # A setup's style can draw its own cursor theme (from the palette)
    if style and hasattr(style, "cursors"):
        cursor = cursor | {"theme": style.cursors(p, ctx) or cursor["theme"]}

    # Quickshell: palette + fonts, in the active setup's shell folder
    write(f"{QS_DIR}/colors.json", json.dumps(
        p | {f"font{k.capitalize()}": fonts[k] for k in FONT_KEYS} | {"fontSize": fonts["size"]},
        indent=2) + "\n")

    # Walker (GTK CSS): colours, and the setup font for everything style.css doesn't override
    write(f"{WALKER_DIR}/colors.css", f"""/* {HEAD} */
@define-color bg       {p["bg"]};
@define-color bg_dark  {p["bgDark"]};
@define-color bg_hl    {p["surface"]};
@define-color border   {p["border"]};
@define-color fg       {p["fg"]};
@define-color fg_dim   {p["dim"]};
@define-color blue     {p["accent"]};
@define-color cyan     {mix(p["accent"], p["purple"], 0.5)};
@define-color magenta  {p["purple"]};
@define-color green    {p["green"]};
@define-color orange   {p["warn"]};
@define-color red      {p["danger"]};
""" + "".join(f"@define-color {k:<8} {v};\n" for k, v in p.items()
              if k not in ("bg", "fg", "border") and v.startswith("#")) + f"""
* {{ font-family: "{fonts["sans"]}", "{fonts["mono"]}", monospace; }}
""")

    # Terminal apps (kitty, btop, Neovim) use the palette with the theme's optional [terminal] table on
    # top, so a light theme can keep a dark terminal (Memphis: an MS-DOS Prompt under grey windows)
    # (and [terminal.syntax] for Neovim's syntax colours)
    tp = p | {k: v for k, v in theme.get("terminal", {}).items() if isinstance(v, str)}
    tsyn = syn | {k: v for k, v in theme.get("terminal", {}).get("syntax", {}).items() if k in SYNTAX_KEYS}

    # Kitty: font, UI colours + the theme's ANSI palette (included last by kitty.conf, so it wins)
    ansi_lines = "".join(f"color{i:<2}                 {ansi[n]}\n" for i, n in enumerate(ANSI_NAMES))
    ansi_lines += "".join(f"color{i + 8:<2}                 {ansi['bright_' + n]}\n"
                          for i, n in enumerate(ANSI_NAMES))
    write(f"{HOME}/.config/kitty/skwd-colors.conf", f"""# {HEAD}
font_family             family="{fonts["mono"]}"
foreground              {tp["fg"]}
background              {tp["bg"]}
selection_foreground    {tp["fg"]}
selection_background    {tp["hover"]}
cursor                  {tp["accent"]}
cursor_text_color       {tp["bg"]}
url_color               {tp["purple"]}
active_border_color     {tp["accent"]}
inactive_border_color   {tp["surface"]}
tab_bar_background      {tp["bgDark"]}
active_tab_foreground   {tp["accent"]}
active_tab_background   {tp["surface"]}
inactive_tab_foreground {tp["dim"]}
inactive_tab_background {tp["bgDark"]}
""" + ansi_lines)
    run("pkill", "-USR1", "-x", "kitty")

    # Hyprland borders (setup.toml [hyprland] border = "gradient" | "accent") and cursor
    # ("palette": the theme's own activeBorder / inactiveBorder keys, e.g. Disguise's hairline greys)
    a, t, b = (p[k].lstrip("#") for k in ("accent", "purple", "border"))
    mode = SETUP.get("hyprland", {}).get("border", "gradient")
    active = (f'{{ colors = {{ "rgba({a}ee)", "rgba({t}ee)" }}, angle = 45 }}' if mode == "gradient"
              else f'"rgba({p.get("activeBorder", p["border"]).lstrip("#")}ff)"' if mode == "palette"
              else f'"rgba({a}ee)"')
    inactive = f'{p.get("inactiveBorder", p["border"]).lstrip("#")}ff' if mode == "palette" else f"{b}aa"
    lua = f"""hl.config({{ general = {{ col = {{
  active_border   = {active},
  inactive_border = "rgba({inactive})",
}} }} }})
"""
    env = (f'hl.env("XCURSOR_THEME", "{cursor["theme"]}")\nhl.env("XCURSOR_SIZE", "{cursor["size"]}")\n'
           f'hl.env("HYPRCURSOR_THEME", "{cursor["theme"]}")\nhl.env("HYPRCURSOR_SIZE", "{cursor["size"]}")\n')
    write(f"{HOME}/.config/hypr/colors.lua", f"-- {HEAD}\n" + lua + env)
    # (hyprctl would read a leading "--" comment as a flag, so eval the code alone)
    run("hyprctl", "eval", lua)
    run("hyprctl", "setcursor", cursor["theme"], str(cursor["size"]))

    # Hyprlock: sourced by hyprlock.conf, read fresh on every lock
    write(f"{HOME}/.config/hypr/hyprlock-colors.conf",
          f"# {HEAD}\n"
          + "".join(f"${k:<11} = rgb({p[k].lstrip('#')})\n"
                    for k in ("bg", "bgDark", "surface", "border", "dim", "fg", "accent",
                              "accentText", "purple", "warn", "danger"))
          + "".join(f"${k:<11} = rgb({v.lstrip('#')})\n" for k, v in p.items()        # a setup's own keys too
                    if k not in ("bg", "bgDark", "surface", "border", "dim", "fg", "accent", "accentText",
                                 "purple", "warn", "danger") and isinstance(v, str) and v.startswith("#"))
          + f"$shade       = rgba({p['bgDark'].lstrip('#')}99)\n"
          + f"$font        = {fonts['mono']}\n$fontDisplay = {fonts['display']}\n")

    write_fonts(fonts, cursor)
    # Icon theme: the setup's style may build one (from the palette); else setup.toml [icons] theme
    icon_theme = (style.icons(p, ctx) if style and hasattr(style, "icons") else None) \
        or theme.get("icons", {}).get("theme") or SETUP.get("icons", {}).get("theme") or "Adwaita"
    write_icons(icon_theme)
    write_satty(p, style, ctx)
    write_gtk(p, style, ctx)
    write_qbittorrent(p, write_qt(p, style, ctx))
    write_btop(tp)
    write_zed(p, ansi, syn, appearance)
    write_nvim(tp, tsyn, theme.get("native_nvim", False))
    write_obsidian(p, fonts)
    write_walker_image(theme["id"])
    write_fastfetch(theme["id"], tp, ansi, (settings or {}).get("fastfetch", {}), cell_ratio)   # it runs in the terminal

    # GTK4/libadwaita apps pick light or dark from this
    run("gsettings", "set", "org.gnome.desktop.interface", "color-scheme",
        "prefer-light" if appearance == "light" else "prefer-dark")

    # OpenRGB is slow (it re-detects hardware), so do it in a detached child
    if openrgb and rgb_follows() and shutil.which("openrgb"):
        subprocess.Popen([os.path.join(os.path.dirname(os.path.abspath(__file__)), "theme"), "openrgb"],
                         stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, start_new_session=True)

    # Walker only reads its CSS at startup; restart the background service
    if shutil.which("walker") and subprocess.run(["pgrep", "-x", "walker"],
                                                  stdout=subprocess.DEVNULL).returncode == 0:
        run("pkill", "-x", "walker")
        subprocess.Popen(["walker", "--gapplication-service"], stdout=subprocess.DEVNULL,
                         stderr=subprocess.DEVNULL, start_new_session=True)

