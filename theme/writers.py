def theme_image(tid, kind):
    """images/<tid>/<kind>.<ext>, else images/_default/<kind>.<ext>; (path, is_default) or (None, True)."""
    for folder, default in ((tid, False), ("_default", True)):
        d = f"{IMAGES}/{folder}"
        try:
            names = sorted(os.listdir(d))
        except OSError:
            continue
        for name in names:
            if os.path.splitext(name)[0] == kind:
                return f"{d}/{name}", default
    return None, True


def image_size(path):
    try:
        out = subprocess.run(["magick", "identify", "-format", "%w %h", path + "[0]"],
                             capture_output=True, text=True, timeout=30).stdout.split()
        return int(out[0]), int(out[1])
    except (OSError, subprocess.SubprocessError, ValueError, IndexError):
        return None


def logo_cells(size, settings, cell_ratio):
    """Terminal cells (width, height) that show an image of size (w, h) px undistorted, fitted
    inside max_width x max_height. A cell is cell_ratio times taller than wide, so an image of
    aspect w/h needs width_cells = height_cells * (w/h) * cell_ratio."""
    max_w, max_h = settings.get("max_width", 65), settings.get("max_height", 30)
    w, h = size
    cols = max_h * (w / h) * cell_ratio
    if cols <= max_w:
        return max(1, round(cols)), max_h
    return max_w, max(1, round(max_w / ((w / h) * cell_ratio)))


def write_walker_image(tid):
    path, _ = theme_image(tid, "walker")
    if not path:
        return
    side = f"{WALKER_DIR}/side.jpg"
    if os.path.islink(side) or not os.path.exists(side):
        tmp = side + ".tmp"
        if os.path.lexists(tmp):
            os.unlink(tmp)
        os.symlink(path, tmp)
        os.replace(tmp, side)  # Walker is restarted after this, so it picks the new image up
    # (a real file there is left alone; it was moved to images/_default/ when this was set up)


def fastfetch_logo(tid, settings, cell_ratio):
    """The picture fastfetch shows for a theme: the theme's image, or, when that's wider than the logo
    box (a desktop wallpaper), a centre-cropped copy in the box's shape. The original is never touched;
    crops live in ~/.cache/theme/fastfetch/ and are only rebuilt when the image or box changes."""
    path, _ = theme_image(tid, "fastfetch")
    if not path or not settings.get("crop", True):
        return path
    size = image_size(path)
    if not size:
        return path
    w, h = size
    # The box is max_width x max_height cells; a cell is cell_ratio times taller than wide
    box_aspect = settings.get("max_width", 65) / (settings.get("max_height", 30) * cell_ratio)
    if w / h <= box_aspect * 1.02:
        return path  # already portrait enough: shown whole
    crop_w = round(h * box_aspect)
    st = os.stat(path)
    out = f"{HOME}/.cache/theme/fastfetch/{tid}-{st.st_ino}-{int(st.st_mtime)}-{crop_w}x{h}.png"
    if not os.path.exists(out):
        os.makedirs(os.path.dirname(out), exist_ok=True)
        for old in os.listdir(os.path.dirname(out)):
            if old.startswith(tid + "-"):
                os.unlink(os.path.join(os.path.dirname(out), old))
        try:
            ok = subprocess.run(["magick", path + "[0]", "-gravity", "center", "-crop", f"{crop_w}x{h}+0+0",
                                 "+repage", "-resize", "1400x1400>", out],
                                stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=60).returncode == 0
        except (OSError, subprocess.SubprocessError):
            ok = False
        if not ok:
            return path
    return out


def write_fastfetch(tid, p, ansi, settings, cell_ratio):
    try:
        with open(f"{SETUP_DIR}/templates/fastfetch.jsonc") as f:
            text = f.read()
    except OSError:
        return
    path = fastfetch_logo(tid, settings, cell_ratio)
    size = image_size(path) if path else None
    width, height = logo_cells(size, settings, cell_ratio) if size else (settings.get("max_width", 65),
                                                                        settings.get("max_height", 30))
    values = {k: ";".join(str(v) for v in rgb(c)) for k, c in p.items() if c.startswith("#")}
    values |= {k: ";".join(str(v) for v in rgb(c)) for k, c in ansi.items() if k not in values}
    values |= {"logo_source": path or "", "logo_width": str(width), "logo_height": str(height)}
    text = text.split("\n", 4)[4] if text.startswith("// Template") else text
    for key, val in values.items():
        text = text.replace("{{%s}}" % key, val)
    write(f"{HOME}/.config/fastfetch/config.jsonc",
          f"// {HEAD}; edit {SETUP_DIR.replace(HOME, '~')}/templates/fastfetch.jsonc\n" + text)


