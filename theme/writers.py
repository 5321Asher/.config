ANSI_NAMES = ("black", "red", "green", "yellow", "blue", "magenta", "cyan", "white")
SYNTAX_KEYS = ("keyword", "function", "string", "type", "constant", "property", "tag", "attribute",
               "operator", "comment")


def rgb(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def hexc(c):
    return "#" + "".join(f"{max(0, min(255, round(v))):02x}" for v in c)


def mix(a, b, t):
    """t=0 -> a, t=1 -> b"""
    ca, cb = rgb(a), rgb(b)
    return hexc(tuple(x + (y - x) * t for x, y in zip(ca, cb)))


def complete(theme):
    """Fill in whatever a theme file leaves out. Returns (palette, ansi, syntax)."""
    p = dict(theme["palette"])
    p.setdefault("bgDark", mix(p["bg"], "#000000", 0.25))
    p.setdefault("surface", mix(p["bg"], p["fg"], 0.08))
    p.setdefault("hover", mix(p["bg"], p["fg"], 0.14))
    p.setdefault("border", mix(p["bg"], p["fg"], 0.2))
    p.setdefault("dim", mix(p["bg"], p["fg"], 0.4))
    p.setdefault("accentText", p["bgDark"])
    p.setdefault("accentMuted", mix(p["bg"], p["accent"], 0.45))
    p.setdefault("purple", p["accent"])
    p.setdefault("warn", "#e0af68")
    p.setdefault("danger", "#f7768e")
    p.setdefault("green", "#9ece6a")
    order = ("bg", "bgDark", "surface", "hover", "border", "dim", "fg", "accent", "accentText",
             "accentMuted", "purple", "warn", "danger", "green")
    p = {k: p[k] for k in order} | {k: v for k, v in p.items() if k not in order}

    given = theme.get("ansi", {})
    ansi = {
        "black": p["bgDark"], "red": p["danger"], "green": p["green"], "yellow": p["warn"],
        "blue": p["accent"], "magenta": p["purple"], "cyan": mix(p["accent"], p["green"], 0.5),
        "white": mix(p["fg"], p["dim"], 0.3),
    } | {k: v for k, v in given.items() if k in ANSI_NAMES}
    for name in ANSI_NAMES:
        ansi["bright_" + name] = given.get("bright_" + name, ansi[name])
    if "bright_black" not in given:
        ansi["bright_black"] = p["dim"]
    if "bright_white" not in given:
        ansi["bright_white"] = p["fg"]

    syntax = {
        "keyword": ansi["magenta"], "function": ansi["blue"], "string": ansi["green"],
        "type": ansi["cyan"], "constant": ansi["yellow"], "property": ansi["bright_cyan"],
        "tag": ansi["red"], "attribute": ansi["yellow"], "operator": mix(p["fg"], p["dim"], 0.5),
        "comment": p["dim"],
    } | {k: v for k, v in theme.get("syntax", {}).items() if k in SYNTAX_KEYS}
    return p, ansi, syntax


def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    tmp = path + ".tmp"
    with open(tmp, "w") as f:
        f.write(text)
    os.replace(tmp, path)


def run(*cmd):
    try:
        subprocess.run(cmd, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=5)
    except (OSError, subprocess.SubprocessError):
        pass


def led_color(hex_color):
    """Theme accents are often pastel; LEDs look washed out unless saturated and bright."""
    h, s, _ = colorsys.rgb_to_hsv(*(c / 255 for c in rgb(hex_color)))
    return hexc(tuple(c * 255 for c in colorsys.hsv_to_rgb(h, max(s, 0.7), 1.0)))


def rgb_follows():
    try:
        with open(RGB_FOLLOW) as f:
            return f.read().strip() != "off"
    except OSError:
        return True


def apply_openrgb(hex_color):
    """Static mode where supported, Direct otherwise; one openrgb call for every device."""
    try:
        listing = subprocess.run(["openrgb", "-ld"], capture_output=True, text=True, timeout=30).stdout
    except (OSError, subprocess.SubprocessError):
        return
    args, index = [], None
    for line in listing.splitlines():
        if line[:1].isdigit() and ": " in line:
            index = line.split(":", 1)[0]
        elif index is not None and line.strip().startswith("Modes:"):
            modes = line.split(":", 1)[1].replace("[", " ").replace("]", " ").replace("'", " ").lower().split()
            mode = "static" if "static" in modes else "direct" if "direct" in modes else None
            if mode:
                args += ["-d", index, "-m", mode, "-c", hex_color.lstrip("#").upper()]
            index = None
    if args:
        run_long("openrgb", *args)


def run_long(*cmd):
    try:
        subprocess.run(cmd, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL, timeout=60)
    except (OSError, subprocess.SubprocessError):
        pass


