def write_satty_palette(p):
    # Annotation colours: theme accents first, then the usual red/orange/green/white/black
    colors = [p["accent"], p["purple"], p["danger"], p["warn"], p["green"], "#ffffff", "#000000"]
    palette = ", ".join(f'"{c}"' for c in colors)
    path = f"{HOME}/.config/satty/config.toml"
    try:
        with open(path) as f:
            base = f.read().split(SATTY_MARK)[0].rstrip() + "\n"
    except OSError:
        return
    write(path, f"""{base}
{SATTY_MARK}
[color-palette]
palette = [{palette}]
""")


