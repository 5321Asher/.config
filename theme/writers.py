def set_ini(path, section, values):
    """Set key=value lines inside [section] of an ini file, keeping everything else."""
    try:
        with open(path) as f:
            lines = f.read().splitlines()
    except OSError:
        lines = []
    if f"[{section}]" not in lines:
        lines += ([""] if lines else []) + [f"[{section}]"]
    i = lines.index(f"[{section}]") + 1
    end = next((j for j in range(i, len(lines)) if lines[j].startswith("[")), len(lines))
    todo = dict(values)
    for j in range(i, end):
        key = lines[j].split("=", 1)[0].strip()
        if key in todo:
            lines[j] = f"{key}={todo.pop(key)}"
    lines[end:end] = [f"{k}={v}" for k, v in todo.items()]
    write(path, "\n".join(lines) + "\n")


