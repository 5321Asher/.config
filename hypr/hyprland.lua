-- Voxtype: while it types a transcription, switch to a submap with no binds so a still-held
-- SUPER/CTRL/ALT can't turn typed letters into shortcuts. ~/.config/voxtype/config.toml
-- enters it (pre_output_command) and leaves it (post_output_command). F12 escapes if voxtype dies mid-type.
hl.define_submap("voxtype_suppress", function()
  for _, key in ipairs({ "SUPER_L", "SUPER_R", "Control_L", "Control_R", "Alt_L", "Alt_R", "Shift_L", "Shift_R" }) do
    hl.bind(key, hl.dsp.no_op())
  end
  hl.bind("F12", hl.dsp.submap("reset"))
end)
